/* Writes libemail/src/core/charset_tables.h from the C library's iconv. */
#include <iconv.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/**
 * @file gen_charset_tables.c
 * @brief Generator of the single-byte character set tables (EMAIL-103).
 *
 * A fully static program cannot rely on the C library's iconv modules (they are
 * loaded from the system, and an empty root has none), so the common
 * single-byte character sets are built in.  The tables are facts taken from
 * the C library of the build machine:
 *
 *     gcc -o /tmp/gen tools/gen_charset_tables.c && /tmp/gen > libemail/src/core/charset_tables.h
 *
 * (run it with a scratch path under build/ in this project).  Bytes 0x00-0x7F
 * are ASCII in all of them; each table holds the code points of 0x80-0xFF, 0
 * for an undefined byte.
 */

static const struct { const char *id; const char *iconv_name; } sets[] = {
    { "iso_8859_1",  "ISO-8859-1" },  { "iso_8859_2",  "ISO-8859-2" },
    { "iso_8859_3",  "ISO-8859-3" },  { "iso_8859_4",  "ISO-8859-4" },
    { "iso_8859_5",  "ISO-8859-5" },  { "iso_8859_6",  "ISO-8859-6" },
    { "iso_8859_7",  "ISO-8859-7" },  { "iso_8859_8",  "ISO-8859-8" },
    { "iso_8859_9",  "ISO-8859-9" },  { "iso_8859_10", "ISO-8859-10" },
    { "iso_8859_13", "ISO-8859-13" }, { "iso_8859_15", "ISO-8859-15" },
    { "iso_8859_16", "ISO-8859-16" },
    { "windows_1250", "CP1250" }, { "windows_1251", "CP1251" },
    { "windows_1252", "CP1252" }, { "windows_1253", "CP1253" },
    { "windows_1254", "CP1254" }, { "windows_1255", "CP1255" },
    { "windows_1256", "CP1256" }, { "windows_1257", "CP1257" },
    { "windows_1258", "CP1258" },
    { "koi8_r", "KOI8-R" }, { "koi8_u", "KOI8-U" },
};

int main(void)
{
    printf("/* SPDX-License-Identifier: GPL-3.0-only */\n"
           "/* Copyright (c) 2026 Peter Csaszar (Császár Péter) */\n"
           "/* Created: 2026-10-16 */\n"
           "/* Single-byte character sets, generated by tools/gen_charset_tables.c. */\n"
           "#ifndef CHARSET_TABLES_H\n#define CHARSET_TABLES_H\n\n"
           "#include <stdint.h>\n\n"
           "/** Code points of the bytes 0x80-0xFF; 0 = undefined. Generated, do not edit. */\n\n");
    for (size_t s = 0; s < sizeof(sets) / sizeof(sets[0]); s++) {
        iconv_t cd = iconv_open("UTF-32LE", sets[s].iconv_name);
        if (cd == (iconv_t)-1) { fprintf(stderr, "no %s\n", sets[s].iconv_name); return 1; }
        printf("static const uint16_t cs_%s[128] = {", sets[s].id);
        for (int b = 0x80; b < 0x100; b++) {
            char in[1] = { (char)b };
            uint32_t out = 0;
            char *ip = in, *op = (char *)&out;
            size_t il = 1, ol = 4;
            iconv(cd, NULL, NULL, NULL, NULL);
            size_t r = iconv(cd, &ip, &il, &op, &ol);
            uint32_t cp = (r == (size_t)-1 || ol != 0) ? 0 : out;
            if (cp > 0xFFFF) { fprintf(stderr, "non-BMP in %s\n", sets[s].iconv_name); return 1; }
            printf("%s0x%04X,", (b - 0x80) % 8 == 0 ? "\n    " : " ", cp);
        }
        printf("\n};\n\n");
        iconv_close(cd);
    }
    printf("#endif /* CHARSET_TABLES_H */\n");
    return 0;
}
